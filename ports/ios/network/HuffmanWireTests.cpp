int main() {
    huffman_t huff{};
    int frequencies[256] = {};
    Huff_Init(&huff);
    Huff_BuildFromData(&huff.compressDecompress, frequencies);
    uint8_t encoded[1024] = {};
    int bit = 0;
    for (int symbol = 0; symbol < 256; ++symbol)
        Huff_offsetTransmit(&huff.compressDecompress, symbol, encoded, &bit);
    assert(bit == 2182);
    assert((bit + 7) / 8 == sizeof(upstream));
    assert(!std::memcmp(encoded, upstream, sizeof(upstream)));
    int offset = 0;
    for (int symbol = 0; symbol < 256; ++symbol) {
        int decoded = -1;
        assert(Huff_offsetReceive(huff.compressDecompress.tree, &decoded, upstream, &offset, bit));
        assert(decoded == symbol);
    }
    assert(offset == bit);
    puts("All 256 symbols match the upstream CoD4x wire fixture");
}
